#!/usr/bin/env python3
"""Generate the bundled aliyah table from Hebcal's leyning data.

The source is the npm package @hebcal/leyning (BSD-2-Clause), file dist/esm/aliyot.json.js.
Fetch it without running any of its code:

    mkdir /tmp/leyning && cd /tmp/leyning && npm pack @hebcal/leyning && tar -xzf hebcal-leyning-*.tgz

then, from the repository root:

    python3 -I scripts/build_aliyot.py /tmp/leyning/package data/ohr_hachaim.sqlite

It writes core/src/shared/kotlin/app/ohrhachaim/core/AliyotData.kt and copies the package licence
to app/src/main/assets/licenses/hebcal-leyning-LICENSE.txt. Every parasha and combined reading
is checked against the Torah verse ranges in the bundled database before anything is written.
Python standard library only.
"""

import json
import os
import sqlite3
import sys

OUT = "core/src/shared/kotlin/app/ohrhachaim/core/AliyotData.kt"
LICENSE_OUT = "app/src/main/assets/licenses/hebcal-leyning-LICENSE.txt"


def place(text):
    chapter, verse = text.split(":")
    return int(chapter), int(verse)


def load_aliyot(package_dir):
    src = open(os.path.join(package_dir, "dist/esm/aliyot.json.js"), encoding="utf-8").read().strip()
    if not src.startswith("export default"):
        sys.exit("unexpected aliyot.json.js format")
    body = src[len("export default"):].split("//# sourceMappingURL")[0].strip().rstrip(";")
    return json.loads(body)


def seven(entry, name):
    kriyah = entry["fullkriyah"]
    rows = []
    for n in range(1, 8):
        start, end = kriyah[str(n)][:2]
        rows.append((place(start), place(end)))
    for (s1, e1), (s2, _) in zip(rows, rows[1:]):
        if not (s1 <= e1 < s2):
            sys.exit(f"{name}: aliyot are not in order: {rows}")
    return rows


def main():
    package_dir, database = sys.argv[1], sys.argv[2]
    meta = json.load(open(os.path.join(package_dir, "package.json"), encoding="utf-8"))
    if meta["name"] != "@hebcal/leyning" or meta["license"] != "BSD-2-Clause":
        sys.exit(f"unexpected package {meta['name']} {meta['license']}")
    data = load_aliyot(package_dir)

    db = sqlite3.connect(f"file:{database}?mode=ro", uri=True)
    torah = {
        row[0]: (row[1], (row[2], row[3]), (row[4], row[5]), row[6])
        for row in db.execute(
            "SELECT id, book_id, torah_start_chapter, torah_start_verse, "
            "torah_end_chapter, torah_end_verse, en_name FROM parashot"
        )
    }
    if sorted(torah) != list(range(1, 55)):
        sys.exit("expected parashot 1-54 in the database")
    combined_weeks = {
        tuple(int(x) for x in row[0].split(","))
        for row in db.execute("SELECT DISTINCT parasha_ids FROM weekly WHERE parasha_ids LIKE '%,%'")
    }

    single = {}
    combined = {}
    for name, entry in data.items():
        if entry.get("combined"):
            ids = (entry["num1"], entry["num2"])
            rows = seven(entry, name)
            book, start, _, _ = torah[ids[0]]
            _, _, end, _ = torah[ids[1]]
            if entry["book"] != book or rows[0][0] != start or rows[-1][1] != end:
                sys.exit(f"{name}: does not cover {start}-{end} in book {book}: {rows}")
            combined[ids] = (name, rows)
        elif isinstance(entry.get("num"), int) and 1 <= entry["num"] <= 54:
            pid = entry["num"]
            rows = seven(entry, name)
            book, start, end, _ = torah[pid]
            if entry["book"] != book or rows[0][0] != start or rows[-1][1] != end:
                sys.exit(f"{name}: does not cover {start}-{end} in book {book}: {rows}")
            single[pid] = (name, rows)
    if sorted(single) != list(range(1, 55)):
        sys.exit(f"missing parashot: {sorted(set(range(1, 55)) - set(single))}")
    missing = combined_weeks - set(combined)
    if missing:
        sys.exit(f"the calendar combines {sorted(missing)}, which the source has no aliyot for")

    def ints(rows):
        return ", ".join(f"{s[0]}, {s[1]}, {e[0]}, {e[1]}" for s, e in rows)

    lines = [
        f"// GENERATED by scripts/build_aliyot.py from {meta['name']} {meta['version']}"
        " (dist/esm/aliyot.json.js). Do not edit by hand.",
        "// Aliyah divisions: Copyright (c) 2020, hebcal. BSD 2-Clause License, reproduced in",
        "// app/src/main/assets/licenses/hebcal-leyning-LICENSE.txt.",
        "package app.ohrhachaim.core",
        "",
        "/**",
        " * The seven aliyot of each parasha, indexed by parasha id 1–54 (index 0 is parasha 1).",
        " * Each row holds 28 numbers: start chapter, start verse, end chapter, end verse, for aliyot 1–7.",
        " */",
        "internal val ALIYOT_SINGLE: Array<IntArray> = arrayOf(",
    ]
    for pid in range(1, 55):
        name, rows = single[pid]
        lines.append(f"    intArrayOf({ints(rows)}), // {pid} {name}")
    lines += [
        ")",
        "",
        "/** The seven aliyot when two parashot are read together, keyed by their ids in order. */",
        "internal val ALIYOT_COMBINED: Map<Pair<Int, Int>, IntArray> = mapOf(",
    ]
    for ids in sorted(combined):
        name, rows = combined[ids]
        lines.append(f"    ({ids[0]} to {ids[1]}) to intArrayOf({ints(rows)}), // {name}")
    lines += [")", ""]

    with open(OUT, "w", encoding="utf-8") as out:
        out.write("\n".join(lines))
    with open(os.path.join(package_dir, "LICENSE"), encoding="utf-8") as src, \
            open(LICENSE_OUT, "w", encoding="utf-8") as dst:
        dst.write(src.read())
    print(f"wrote {OUT}: 54 parashot, {len(combined)} combined readings, from {meta['version']}")


if __name__ == "__main__":
    main()
