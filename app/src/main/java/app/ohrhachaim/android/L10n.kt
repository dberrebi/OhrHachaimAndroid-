/**
 * Interface strings copied from the iOS String Catalog (commit 25208b8), with the help text's
 * iOS-only wording (VoiceOver, Home Screen) changed to its Android equivalent.
 * Commentary text never goes through this type. Placeholders are `%s` for [String.format].
 */
object L10n {
    fun text(key: String, language: AppLanguage): String {
        val table = if (language == AppLanguage.HE) HE else EN
        return table[key] ?: key
    }

    fun format(key: String, language: AppLanguage, vararg args: Any?): String {
        val pattern = text(key, language)
        return String.format(Locale.US, pattern, *args)
    }

